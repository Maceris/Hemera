"""
Writes std/unicode/normalization_tables.hsc from the Unicode Character Database.

    python generate_normalization.py <ucd folder>

The folder holds, from https://www.unicode.org/Public/<version>/ucd/: UnicodeData.txt, DerivedNormalizationProps.txt
and CaseFolding.txt, for the tables, and NormalizationTest.txt, for the tests: its parts 0 and 2 to 5 whole, and every
tenth line of part 1, character by character, are copied beside the tables as test/normalization_test.txt.

The tables: each code point's canonical combining class, as runs; each canonical decomposition, whole (decomposed
again until nothing in it decomposes), but Hangul syllables', which are worked out; each pair two code points compose
into, but those excluded from composition; and each full case folding (statuses C and F).
"""

import os
import re
import sys


def lines_of(path):
    """Each line's fields, split at ';', without its comment; blank lines left out."""
    with open(path, encoding="utf-8") as file:
        for line in file:
            line = line.split("#", 1)[0].strip()
            if line:
                yield [field.strip() for field in line.split(";")]


def rows(items, per_line, digits):
    lines = []
    for i in range(0, len(items), per_line):
        lines.append("    " + ", ".join(f"0x{item:0{digits}x}" for item in items[i:i + per_line]) + ",")
    return "\n".join(lines)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    ucd = sys.argv[1]
    here = os.path.dirname(os.path.abspath(__file__))
    package = os.path.dirname(here)
    with open(os.path.join(ucd, "DerivedNormalizationProps.txt"), encoding="utf-8") as file:
        match = re.search(r"DerivedNormalizationProps-(\d+\.\d+\.\d+)", file.readline())
        version = match.group(1) if match else "unknown"

    classes = {}
    decompositions = {}
    for fields in lines_of(os.path.join(ucd, "UnicodeData.txt")):
        point = int(fields[0], 16)
        if fields[3] != "0":
            classes[point] = int(fields[3])
        mapping = fields[5]
        if mapping and not mapping.startswith("<"):
            decompositions[point] = [int(part, 16) for part in mapping.split()]
    excluded = set()
    for fields in lines_of(os.path.join(ucd, "DerivedNormalizationProps.txt")):
        if fields[1] == "Full_Composition_Exclusion":
            points = fields[0].split("..")
            for point in range(int(points[0], 16), int(points[-1], 16) + 1):
                excluded.add(point)

    def full(point):
        """A code point's canonical decomposition, decomposed again until nothing in it does."""
        if point not in decompositions:
            return [point]
        made = []
        for part in decompositions[point]:
            made.extend(full(part))
        return made

    decomposed = sorted(decompositions)
    decomposition_starts = []
    decomposition_data = []
    for point in decomposed:
        decomposition_starts.append(len(decomposition_data))
        decomposition_data.extend(full(point))
    decomposition_starts.append(len(decomposition_data))
    longest = max(decomposition_starts[i + 1] - decomposition_starts[i] for i in range(len(decomposed)))

    pairs = []
    for point, mapping in decompositions.items():
        if len(mapping) == 2 and point not in excluded:
            pairs.append(((mapping[0] << 21) | mapping[1], point))
    pairs.sort()

    class_starts = []
    class_values = []
    for point in range(0x110000):
        value = classes.get(point, 0)
        if point == 0 or value != classes.get(point - 1, 0):
            class_starts.append(point)
            class_values.append(value)

    folded = {}
    for fields in lines_of(os.path.join(ucd, "CaseFolding.txt")):
        if fields[1] in ("C", "F"):
            folded[int(fields[0], 16)] = [int(part, 16) for part in fields[2].split()]
    fold_points = sorted(folded)
    fold_starts = []
    fold_data = []
    for point in fold_points:
        fold_starts.append(len(fold_data))
        fold_data.extend(folded[point])
    fold_starts.append(len(fold_data))

    text = f"""package unicode

// Generated by _generator/generate_normalization.py from the Unicode Character Database {version}; don't edit.

/** The most code points a canonical decomposition has, whole: what one code point can become in NFD. */
LONGEST_DECOMPOSITION :: {longest}

/** The first code point of each run of code points with the same canonical combining class, ascending, from 0. */
CLASS_STARTS :: u32.[
{rows(class_starts, 10, 6)}
]

/** Each run's canonical combining class: 0 for a starter. */
CLASS_VALUES :: u8.[
{rows(class_values, 16, 2)}
]

/** The code points with a canonical decomposition, ascending; Hangul syllables', worked out, aren't here. */
DECOMPOSED :: u32.[
{rows(decomposed, 10, 6)}
]

/** Where each of DECOMPOSED's decompositions starts in DECOMPOSITIONS, and, last, where the last one ends. */
DECOMPOSITION_STARTS :: u16.[
{rows(decomposition_starts, 12, 4)}
]

/** The decompositions, whole, one after another. */
DECOMPOSITIONS :: u32.[
{rows(decomposition_data, 10, 6)}
]

/** The pairs that compose, as the first code point shifted left 21 bits ORed with the second, ascending. */
COMPOSED_PAIRS :: u64.[
{rows([key for key, _ in pairs], 6, 11)}
]

/** What each of COMPOSED_PAIRS composes into. */
COMPOSITES :: u32.[
{rows([value for _, value in pairs], 10, 6)}
]

/** The code points full case folding changes, ascending. */
FOLDED :: u32.[
{rows(fold_points, 10, 6)}
]

/** Where each of FOLDED's foldings starts in FOLDINGS, and, last, where the last one ends. */
FOLDING_STARTS :: u16.[
{rows(fold_starts, 12, 4)}
]

/** The foldings, one after another: 1 to 3 code points each. */
FOLDINGS :: u32.[
{rows(fold_data, 10, 6)}
]
"""
    with open(os.path.join(package, "normalization_tables.hsc"), "w", encoding="utf-8", newline="\n") as file:
        file.write(text)

    # The test file: parts 0 and 2 to 5 whole, part 1 a line in ten
    kept = []
    part = None
    counted = 0
    with open(os.path.join(ucd, "NormalizationTest.txt"), encoding="utf-8") as file:
        for line in file:
            if line.startswith("@Part"):
                part = line.split()[0]
                kept.append(line)
                continue
            if part == "@Part1" and line.strip() and not line.startswith("#"):
                counted += 1
                if counted % 10 != 1:
                    continue
            kept.append(line)
    test_folder = os.path.join(package, "test")
    os.makedirs(test_folder, exist_ok=True)
    with open(os.path.join(test_folder, "normalization_test.txt"), "w", encoding="utf-8", newline="\n") as file:
        file.writelines(kept)
    print(f"{len(decomposed)} decompositions, {len(pairs)} compositions, {len(fold_points)} foldings, "
          f"{len(class_starts)} class runs, from Unicode {version}")


if __name__ == "__main__":
    main()
